import {execFileSync} from 'node:child_process';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const commit=execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
const html=await readFile('dist/index.html','utf8');
const entry=html.match(/"js":\["([^"]+\.js)"/)?.[1] || (html.includes('ciac/adapter.js') ? (html.includes('./main.js') ? 'main.js' : 'js/main.js') : null);
if(!entry)throw Error('Missing game entrypoint');
const bytes=await readFile('dist/'+entry.replace(/^\//,''));
const files = html.includes('ciac/adapter.js') ? (entry==='main.js' ? ['main.js','ciac/adapter.js','ciac/adapter.css','gl-matrix.js'] : ['js/main.js','ciac/adapter.js','ciac/adapter.css','lib/three.min.js']) : [entry];
const hashes=Object.fromEntries(await Promise.all(files.map(async file=>[file,createHash('sha256').update(await readFile('dist/'+file)).digest('hex')])));
await writeFile('dist/build.json',JSON.stringify({commit,entry,sha256:createHash('sha256').update(bytes).digest('hex'),files:hashes})+'\n');
